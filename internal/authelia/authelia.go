// Package authelia renders Authelia's configuration and users file from
// Marineris state.
//
// Secrets (JWT, session and storage keys) are never written into the
// rendered files: Authelia reads them from files through its *_FILE
// environment variables, which the compose stack sets.
package authelia

import (
	"errors"
	"fmt"
	"sort"

	"gopkg.in/yaml.v3"

	"github.com/photonring/marineris-server/internal/store"
	"github.com/photonring/marineris-server/internal/validate"
)

// PlaceholderDomain is used for the session cookie before any domain is
// configured, so Authelia can start (and stay unreachable) during setup.
const PlaceholderDomain = "marineris-setup.internal"

// Paths inside the Authelia container.
const (
	UsersFile        = "/config/users_database.yml"
	DataDir          = "/data"
	NotificationFile = "/notifications/notification.txt"
)

// User is an Authelia user rendered into the users file.
type User struct {
	Username     string
	DisplayName  string
	Email        string
	PasswordHash string
	Groups       []string
	Disabled     bool
}

// Input is everything the configuration is rendered from.
type Input struct {
	Settings store.Settings
	Domains  []string
	// ProtectedHosts are hosts whose routes use the Authelia policy.
	ProtectedHosts []string
	Users          []User
}

// Render returns configuration.yml and users_database.yml.
func Render(in Input) (config, users []byte, err error) {
	if err := Validate(in); err != nil {
		return nil, nil, err
	}
	cfg, err := yaml.Marshal(configDoc(in))
	if err != nil {
		return nil, nil, err
	}
	usr, err := yaml.Marshal(usersDoc(in.Users))
	if err != nil {
		return nil, nil, err
	}
	header := []byte("# Generated by Marineris. Do not edit: changes are overwritten.\n")
	return append(append([]byte{}, header...), cfg...), append(append([]byte{}, header...), usr...), nil
}

// Validate checks the input.
func Validate(in Input) error {
	var problems []string
	for _, d := range in.Domains {
		if err := validate.Zone(d); err != nil {
			problems = append(problems, fmt.Sprintf("domain %q: %v", d, err))
		}
	}
	for _, h := range in.ProtectedHosts {
		if err := validate.Hostname(h); err != nil {
			problems = append(problems, fmt.Sprintf("host %q: %v", h, err))
		}
	}
	for _, u := range in.Users {
		if u.Username == "" || u.PasswordHash == "" {
			problems = append(problems, "user without name or password")
		}
	}
	if len(problems) > 0 {
		return fmt.Errorf("invalid Authelia input: %v", problems)
	}
	if err := validate.Hostname(in.Settings.AuthSubdomain + ".example.com"); err != nil {
		return errors.New("invalid auth subdomain")
	}
	return nil
}

type m = map[string]any

func configDoc(in Input) m {
	domains := append([]string(nil), in.Domains...)
	sort.Strings(domains)
	var cookies []m
	for _, d := range domains {
		cookies = append(cookies, m{
			"domain":       d,
			"authelia_url": "https://" + in.Settings.AuthSubdomain + "." + d,
		})
	}
	if len(cookies) == 0 {
		cookies = append(cookies, m{
			"domain":       PlaceholderDomain,
			"authelia_url": "https://auth." + PlaceholderDomain,
		})
	}

	hosts := append([]string(nil), in.ProtectedHosts...)
	sort.Strings(hosts)
	hosts = dedupe(hosts)
	rules := []m{}
	if len(hosts) > 0 {
		rules = append(rules, m{"domain": hosts, "policy": "two_factor"})
	} else {
		// Authelia refuses default_policy "deny" without any rule; add an
		// inert one so the default stays deny-all.
		rules = append(rules, m{"domain": []string{"deny." + PlaceholderDomain}, "policy": "deny"})
	}

	return m{
		// disable_healthcheck: Authelia would otherwise write a helper file
		// into /app, which is impossible on the read-only root filesystem.
		// compose.yml probes /api/health instead.
		"server": m{"address": "tcp://:9091/", "disable_healthcheck": true},
		"log":    m{"level": "info", "format": "json"},
		"theme":  "dark",
		"totp": m{
			"issuer":    "Marineris",
			"algorithm": "SHA1",
			"digits":    6,
			"period":    30,
			"skew":      1,
		},
		"webauthn": m{
			"disable":                           false,
			"enable_passkey_login":              true,
			"display_name":                      "Marineris",
			"attestation_conveyance_preference": "indirect",
			"timeout":                           "60s",
			"selection_criteria": m{
				"user_verification": "preferred",
				"discoverability":   "preferred",
			},
		},
		"authentication_backend": m{
			"password_reset": m{"disable": true},
			"file": m{
				"path":  UsersFile,
				"watch": true,
				"password": m{
					"algorithm": "argon2",
					"argon2": m{
						"variant":     "argon2id",
						"iterations":  3,
						"memory":      65536,
						"parallelism": 4,
						"key_length":  32,
						"salt_length": 16,
					},
				},
			},
		},
		"password_policy": m{
			"standard": m{"enabled": true, "min_length": 12, "max_length": 256},
		},
		"access_control": m{
			"default_policy": "deny",
			"rules":          rules,
		},
		"session": m{
			"name":        "marineris_auth_session",
			"same_site":   "lax",
			"inactivity":  "30m",
			"expiration":  "12h",
			"remember_me": -1,
			"cookies":     cookies,
		},
		"regulation": m{
			"max_retries": 5,
			"find_time":   "10m",
			"ban_time":    "30m",
		},
		"storage": m{
			"local": m{"path": DataDir + "/db.sqlite3"},
		},
		"notifier": m{
			"disable_startup_check": true,
			"filesystem":            m{"filename": NotificationFile},
		},
		"ntp": m{"disable_startup_check": true},
	}
}

// placeholderHash is an argon2id hash of a random value that was discarded
// when this file was written: nobody knows a matching password. It is only
// used for the disabled placeholder account below.
const placeholderHash = "$argon2id$v=19$m=65536,t=3,p=4$4tq3N6pJ7Hq8yXv2kQ1f0w$9w0fL2B4n6eQ1mZpY3uV8sK5hR7cT0aXdJ2iG4oF6bE"

// PlaceholderUser is rendered when no administrator exists yet: Authelia
// refuses to start with an empty users file. The account is disabled.
const PlaceholderUser = "marineris-placeholder"

func usersDoc(users []User) m {
	out := m{}
	if len(users) == 0 {
		out[PlaceholderUser] = m{
			"disabled":    true,
			"displayname": "Disabled placeholder",
			"password":    placeholderHash,
			"email":       "placeholder@" + PlaceholderDomain,
			"groups":      []string{},
		}
	}
	for _, u := range users {
		groups := u.Groups
		if groups == nil {
			groups = []string{}
		}
		name := u.DisplayName
		if name == "" {
			name = u.Username
		}
		out[u.Username] = m{
			"disabled":    u.Disabled,
			"displayname": name,
			"password":    u.PasswordHash,
			"email":       u.Email,
			"groups":      groups,
		}
	}
	return m{"users": out}
}

func dedupe(sorted []string) []string {
	out := sorted[:0]
	for i, s := range sorted {
		if i == 0 || s != sorted[i-1] {
			out = append(out, s)
		}
	}
	return out
}
