// Package authelia renders Authelia's configuration and users file from
// Marineris state.
//
// Secrets (JWT, session and storage keys) are never written into the
// rendered files: Authelia reads them from files through its *_FILE
// environment variables, which the compose stack sets.
package authelia

import (
	"errors"
	"fmt"
	"maps"
	"regexp"
	"slices"
	"sort"

	"gopkg.in/yaml.v3"

	"github.com/photonring/marineris-server/internal/store"
	"github.com/photonring/marineris-server/internal/validate"
)

// PlaceholderDomain is used for the session cookie before any domain is
// configured, so Authelia can start (and stay unreachable) during setup.
const PlaceholderDomain = "marineris-setup.internal"

// SessionStoreHost is Valkey, Authelia's session store (compose.yml).
const SessionStoreHost = "valkey"

// Paths inside the Authelia container.
const (
	UsersFile        = "/config/users_database.yml"
	DataDir          = "/data"
	NotificationFile = "/notifications/notification.txt"
)

// User is an Authelia user rendered into the users file.
type User struct {
	Username     string
	DisplayName  string
	Email        string
	PasswordHash string
	Groups       []string
	Disabled     bool
}

// Input is everything the configuration is rendered from.
type Input struct {
	Settings store.Settings
	Domains  []string
	// Protected are the routes behind Authelia.
	Protected []Resource
	Users     []User
}

// AdminsGroup is the Authelia group of Marineris administrators.
const AdminsGroup = "admins"

// Resource is a host, optionally narrowed to a path prefix ("/app"), that
// needs a two-factor login; AdminOnly restricts it to AdminsGroup.
type Resource struct {
	Host       string
	PathPrefix string
	AdminOnly  bool
}

// Render returns configuration.yml and users_database.yml.
func Render(in Input) (config, users []byte, err error) {
	if err := Validate(in); err != nil {
		return nil, nil, err
	}
	cfg, err := yaml.Marshal(configDoc(in))
	if err != nil {
		return nil, nil, err
	}
	usr, err := yaml.Marshal(usersDoc(in.Users))
	if err != nil {
		return nil, nil, err
	}
	header := []byte("# Generated by Marineris. Do not edit: changes are overwritten.\n")
	return append(append([]byte{}, header...), cfg...), append(append([]byte{}, header...), usr...), nil
}

// Validate checks the input.
func Validate(in Input) error {
	var problems []string
	for _, d := range in.Domains {
		if err := validate.Zone(d); err != nil {
			problems = append(problems, fmt.Sprintf("domain %q: %v", d, err))
		}
	}
	for _, res := range in.Protected {
		if err := validate.Hostname(res.Host); err != nil {
			problems = append(problems, fmt.Sprintf("host %q: %v", res.Host, err))
		}
		if err := validate.PathPrefix(res.PathPrefix); err != nil {
			problems = append(problems, fmt.Sprintf("path %q: %v", res.PathPrefix, err))
		}
	}
	for _, u := range in.Users {
		if u.Username == "" || u.PasswordHash == "" {
			problems = append(problems, "user without name or password")
		}
	}
	if len(problems) > 0 {
		return fmt.Errorf("invalid Authelia input: %v", problems)
	}
	if err := validate.Hostname(in.Settings.AuthSubdomain + ".example.com"); err != nil {
		return errors.New("invalid auth subdomain")
	}
	return nil
}

type m = map[string]any

func configDoc(in Input) m {
	domains := append([]string(nil), in.Domains...)
	sort.Strings(domains)
	var cookies []m
	for _, d := range domains {
		cookies = append(cookies, m{
			"domain":       d,
			"authelia_url": "https://" + in.Settings.AuthSubdomain + "." + d,
		})
	}
	if len(cookies) == 0 {
		cookies = append(cookies, m{
			"domain":       PlaceholderDomain,
			"authelia_url": "https://auth." + PlaceholderDomain,
		})
	}

	// Authelia applies the first matching rule: the most specific resources
	// come first. An admin-only resource lets members of the admins group in
	// with two factors and denies everyone else before a broader rule for
	// the same host can match.
	rules := []m{}
	for _, res := range resources(in.Protected) {
		rule := m{"domain": []string{res.Host}}
		if res.PathPrefix != "" {
			rule["resources"] = []string{"^" + regexp.QuoteMeta(res.PathPrefix) + "([/?#].*)?$"}
		}
		if !res.AdminOnly {
			rule["policy"] = "two_factor"
			rules = append(rules, rule)
			continue
		}
		allow := maps.Clone(rule)
		allow["subject"] = []string{"group:" + AdminsGroup}
		allow["policy"] = "two_factor"
		rule["policy"] = "deny"
		rules = append(rules, allow, rule)
	}
	if len(rules) == 0 {
		// Authelia refuses default_policy "deny" without any rule; add an
		// inert one so the default stays deny-all.
		rules = append(rules, m{"domain": []string{"deny." + PlaceholderDomain}, "policy": "deny"})
	}

	return m{
		// disable_healthcheck: Authelia would otherwise write a helper file
		// into /app, which is impossible on the read-only root filesystem.
		// compose.yml probes /api/health instead.
		// asset_path: the brand's logo and favicon, written by Marineris.
		"server": m{"address": "tcp://:9091/", "disable_healthcheck": true, "asset_path": "/config/assets/"},
		"log":    m{"level": "info", "format": "json"},
		"theme":  "dark",
		"totp": m{
			"issuer":    "Marineris",
			"algorithm": "SHA1",
			"digits":    6,
			"period":    30,
			"skew":      1,
		},
		"webauthn": m{
			"disable":              false,
			"enable_passkey_login": true,
			// A passkey unlocked on the device (Face ID, fingerprint, PIN) is
			// two factors: it signs in alone, like everywhere else.
			"experimental_enable_passkey_uv_two_factors": true,
			"display_name":                      "Marineris",
			"attestation_conveyance_preference": "indirect",
			"timeout":                           "60s",
			"selection_criteria": m{
				"user_verification": "preferred",
				// Passkey sign-in has no username: the passkey must tell
				// Authelia whose it is (discoverable credential).
				"discoverability": "required",
			},
		},
		"authentication_backend": m{
			"password_reset": m{"disable": true},
			"file": m{
				"path":  UsersFile,
				"watch": true,
				"password": m{
					"algorithm": "argon2",
					"argon2": m{
						"variant":     "argon2id",
						"iterations":  3,
						"memory":      65536,
						"parallelism": 4,
						"key_length":  32,
						"salt_length": 16,
					},
				},
			},
		},
		"password_policy": m{
			"standard": m{"enabled": true, "min_length": 12, "max_length": 256},
		},
		"access_control": m{
			"default_policy": "deny",
			"rules":          rules,
		},
		"session": m{
			"name":        "marineris_auth_session",
			"same_site":   "lax",
			"inactivity":  "30m",
			"expiration":  "12h",
			"remember_me": -1,
			"cookies":     cookies,
			// Sessions live in Valkey, not in Authelia's memory: restarting
			// Authelia (every configuration change, upgrades) keeps everyone
			// signed in.
			"redis": m{"host": SessionStoreHost, "port": 6379},
		},
		// Actions that need a confirmed identity (registering a passkey in
		// the portal) rely on the second factor of the sign-in instead of a
		// one-time code sent by e-mail: Marineris registers every user's
		// authenticator, and a password-only session is never enough.
		"identity_validation": m{
			"elevated_session": m{"require_second_factor": true, "skip_second_factor": true},
		},
		"regulation": m{
			"max_retries": 5,
			"find_time":   "10m",
			"ban_time":    "30m",
		},
		"storage": m{
			"local": m{"path": DataDir + "/db.sqlite3"},
		},
		"notifier": m{
			"disable_startup_check": true,
			"filesystem":            m{"filename": NotificationFile},
		},
		"ntp": m{"disable_startup_check": true},
	}
}

// placeholderHash is an argon2id hash of a random value that was discarded
// when this file was written: nobody knows a matching password. It is only
// used for the disabled placeholder account below.
const placeholderHash = "$argon2id$v=19$m=65536,t=3,p=4$4tq3N6pJ7Hq8yXv2kQ1f0w$9w0fL2B4n6eQ1mZpY3uV8sK5hR7cT0aXdJ2iG4oF6bE"

// PlaceholderUser is rendered when no administrator exists yet: Authelia
// refuses to start with an empty users file. The account is disabled.
const PlaceholderUser = "marineris-placeholder"

func usersDoc(users []User) m {
	out := m{}
	if len(users) == 0 {
		out[PlaceholderUser] = m{
			"disabled":    true,
			"displayname": "Disabled placeholder",
			"password":    placeholderHash,
			"email":       "placeholder@" + PlaceholderDomain,
			"groups":      []string{},
		}
	}
	for _, u := range users {
		groups := u.Groups
		if groups == nil {
			groups = []string{}
		}
		name := u.DisplayName
		if name == "" {
			name = u.Username
		}
		out[u.Username] = m{
			"disabled":    u.Disabled,
			"displayname": name,
			"password":    u.PasswordHash,
			"email":       u.Email,
			"groups":      groups,
		}
	}
	return m{"users": out}
}

// resources sorts resources by host, longest path prefix first, and merges
// duplicates (admin-only wins).
func resources(in []Resource) []Resource {
	out := append([]Resource(nil), in...)
	sort.SliceStable(out, func(i, j int) bool {
		a, b := out[i], out[j]
		if a.Host != b.Host {
			return a.Host < b.Host
		}
		if len(a.PathPrefix) != len(b.PathPrefix) {
			return len(a.PathPrefix) > len(b.PathPrefix)
		}
		if a.PathPrefix != b.PathPrefix {
			return a.PathPrefix < b.PathPrefix
		}
		return a.AdminOnly && !b.AdminOnly
	})
	return slices.CompactFunc(out, func(a, b Resource) bool { return a.Host == b.Host && a.PathPrefix == b.PathPrefix })
}
